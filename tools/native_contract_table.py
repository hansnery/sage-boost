"""Generate runtime fingerprints/dependency metadata; never emit function bodies."""
import os
import zlib
from pathlib import Path
from test_fx_lifecycle import BASELINE, fnv1a
from verify_sites import Image
from port_sites import port

ROOT = Path(__file__).resolve().parents[1]


def render(reference, module, name, prefix, option, roots, exports):
    identities = [r for r, _ in module.BODIES] + sorted(module.EXCEPTIONS) + sorted(getattr(module, 'EXTERNALS', {}))
    symbols = {r: i for i, r in enumerate(identities)}
    assert len(symbols) == len(identities)
    patches, bodies, signatures = [], [], []
    for rva, size in module.BODIES:
        normalized, relocations = module.recipe(reference, rva, size)
        bodies.append((size, len(patches), len(relocations), fnv1a(normalized), zlib.crc32(normalized)))
        patches.extend((off, kind, symbols[target]) for off, kind, target in relocations)
    for index, length in roots:
        rva, size = module.BODIES[index]
        assert 5 <= length <= size
        _, relocations = module.recipe(reference, rva, size)
        wildcard = {off + i for off, _, _ in relocations for i in range(4)}
        raw = reference.mem[rva:rva+length]
        signatures.append(' '.join('??' if i in wildcard else f'{b:02X}' for i, b in enumerate(raw)))
    lower = prefix.lower()
    lines = [f'/* Generated by tools/verify_sites.py {option} --write. */',
             f'#ifndef PF_{name.upper()}_TABLE_H', f'#define PF_{name.upper()}_TABLE_H',
             '#include "nativecontract.h"', '',
             f'#define {prefix}_BODY_COUNT {len(bodies)}u', f'#define {prefix}_SYMBOL_COUNT {len(identities)}u']
    lines += [f'#define {prefix}_{key} {index}u' for key, index in exports.items()]
    for i, signature in enumerate(signatures):
        key = f'{prefix}_SIGNATURE' if not i else f'{prefix}_ROOT_{i}_SIGNATURE'
        lines.append(f'#define {key} "{signature}"')
    lines += ['', f'static const pf_contract_body {lower}_bodies[] = {{']
    lines += [f'    {{{s}, {first}, {n}, 0x{fnv:08X}u, 0x{crc:08X}u}},' for s, first, n, fnv, crc in bodies]
    lines += ['};', f'static const pf_contract_patch {lower}_patches[] = {{']
    lines += [f'    {{{off}, {kind}, {symbol}, 0}},' for off, kind, symbol in patches]
    roles = [int(any(s.VirtualAddress <= r < s.VirtualAddress+s.Misc_VirtualSize and
                     s.Characteristics & 0x20000000 for s in reference.pe.sections)) for r in identities]
    lines += ['};', '/* 1 = executable code, 0 = readable non-executable dependency data. */',
              f'static const unsigned char {lower}_code[] = {{',
              '    ' + ', '.join(map(str, roles)), '};',
              f'static const pf_contract_root {lower}_roots[] = {{']
    for i, (index, _) in enumerate(roots):
        key = f'{prefix}_SIGNATURE' if not i else f'{prefix}_ROOT_{i}_SIGNATURE'
        lines.append(f'    {{{index}, {key}}},')
    lines += ['};', f'static const pf_native_contract {lower}_contract = {{',
              f'    {prefix}_BODY_COUNT, {prefix}_SYMBOL_COUNT, {len(patches)}, {len(roots)},',
              f'    {lower}_bodies, {lower}_patches, {lower}_code, {lower}_roots, NULL, NULL', '};', '', '#endif', '']
    return '\n'.join(lines)


def run(write, module, name, prefix, option, roots, exports):
    reference = Image(BASELINE)
    for variable, default in [('AOTR_DAT', 'C:/Jogos/AgeoftheRing/rotwk/game.dat'),
                              ('ROTWK_DAT', 'C:/Jogos/AgeoftheRing/rotwk/game820.dat')]:
        target = Image(Path(os.environ.get(variable, default)))
        module.verify(reference, target)
        for index, length in roots:
            _, hits = port(reference, module.BODIES[index][0], target, lengths=(length,))
            assert len(hits) == 1, 'runtime root signature is not unique'
    content = render(reference, module, name, prefix, option, roots, exports)
    header = ROOT / f'perf/src/{name}_table.h'
    if header.exists() and header.read_text(encoding='utf-8') == content:
        print(f'Runtime {name} table: up to date')
    elif write:
        header.write_text(content, encoding='utf-8', newline='\n')
        print(f'Runtime {name} table: written')
    else:
        raise AssertionError(f'runtime {name} table is stale; run {option} --write')
    return 0
