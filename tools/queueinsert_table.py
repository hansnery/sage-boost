"""Generate hash/dependency metadata for the runtime task insertion guard.

Only the short wildcard entry signature is emitted as instruction bytes.
The remaining contract consists of hashes, lengths and symbolic relocations.
Research RVAs are used to read the reference, never emitted as runtime sites.
"""
import os
import zlib
from pathlib import Path

from bench_native_insert import BODIES, EXCEPTIONS, EXTERNALS, recipe, verify
from test_fx_lifecycle import BASELINE, fnv1a
from verify_sites import Image

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'perf/src/queueinsert_table.h'
DATA = {0x87C738, 0x87C748, 0x87C768, 0x87C778}


def render(reference):
    identities = [r for r, _ in BODIES] + sorted(EXCEPTIONS) + sorted(EXTERNALS)
    symbols = {r: i for i, r in enumerate(identities)}
    patches, bodies = [], []
    for rva, size in BODIES:
        normalized, relocations = recipe(reference, rva, size)
        bodies.append((size, len(patches), len(relocations), fnv1a(normalized), zlib.crc32(normalized)))
        patches.extend((off, kind, symbols[target]) for off, kind, target in relocations)
    raw = reference.mem[BODIES[0][0]:BODIES[0][0]+48]
    _, root_patches = recipe(reference, *BODIES[0])
    wildcard = {off+i for off, _, _ in root_patches for i in range(4)}
    signature = ' '.join('??' if i in wildcard else f'{b:02X}' for i, b in enumerate(raw))
    lines = ['/* Generated by tools/verify_sites.py --perf-queue --write. */',
             '#ifndef PF_QUEUEINSERT_TABLE_H', '#define PF_QUEUEINSERT_TABLE_H', '',
             f'#define QI_BODY_COUNT {len(bodies)}u', f'#define QI_SYMBOL_COUNT {len(identities)}u',
             f'#define QI_MAX_BODY {max(s for _, s in BODIES)}u',
             f'#define QI_SIGNATURE "{signature}"', '',
             'typedef struct { unsigned size, first, count, fnv, crc; } qi_body;',
             'typedef struct { unsigned offset, absolute, symbol; } qi_patch;',
             'static const qi_body qi_bodies[] = {']
    lines += [f'    {{{s}, {first}, {n}, 0x{fnv:08X}u, 0x{crc:08X}u}},' for s, first, n, fnv, crc in bodies]
    lines += ['};', 'static const qi_patch qi_patches[] = {']
    lines += [f'    {{{off}, {kind}, {symbol}}},' for off, kind, symbol in patches]
    lines += ['};', '/* 1 = executable code, 0 = readable non-executable exception data. */',
              'static const unsigned char qi_code[] = {',
              '    '+', '.join(str(int(r not in DATA)) for r in identities), '};', '', '#endif', '']
    return '\n'.join(lines)


def run(write):
    reference = Image(BASELINE)
    for variable, default in [('AOTR_DAT', 'C:/Jogos/AgeoftheRing/rotwk/game.dat'),
                              ('ROTWK_DAT', 'C:/Jogos/AgeoftheRing/rotwk/game820.dat')]:
        path = Path(os.environ.get(variable, default))
        target = Image(path)
        verify(reference, target)
        # The shorter runtime anchor must still be unique in both images.
        from port_sites import port
        _, hits = port(reference, BODIES[0][0], target, lengths=(48,))
        assert len(hits) == 1, 'short queue entry signature is not unique'
    content = render(reference)
    if HEADER.exists() and HEADER.read_text(encoding='utf-8') == content:
        print('Runtime queue insertion table: up to date')
    elif write:
        HEADER.write_text(content, encoding='utf-8', newline='\n')
        print('Runtime queue insertion table: written')
    else:
        raise AssertionError('runtime queue table is stale; run --perf-queue --write')
    return 0
