/* The DLL links no C runtime; GCC may still emit calls to these. Built with
 * -fno-tree-loop-distribute-patterns so the loops are not turned back into
 * calls to themselves. */
#include <stddef.h>

void *memcpy(void *dst, const void *src, size_t n)
{
    unsigned char *d = dst;
    const unsigned char *s = src;
    while (n--)
        *d++ = *s++;
    return dst;
}

void *memset(void *dst, int c, size_t n)
{
    unsigned char *d = dst;
    while (n--)
        *d++ = (unsigned char)c;
    return dst;
}
