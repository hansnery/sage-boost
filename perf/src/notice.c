#define PF_NOTICE_BG 0xFF202020u
#define PF_NOTICE_FG 0xFFFFD040u
#define PF_D3DCLEAR_TARGET 1u
#define PF_D3DRS_SCISSORTESTENABLE 174u

const unsigned char *pf_notice_glyph(char c)
{
    unsigned char u = (unsigned char)c;
    return g_font[u >= 32 && u <= 126 ? u - 32 : '?' - 32];
}

void pf_notice_text(const char *text, char *out, unsigned cap)
{
    unsigned len = 0, i;

    if (!cap)
        return;
    while (text[len])
        len++;
    while (len && (text[len - 1] == '.' || text[len - 1] == ' '))
        len--;
    if (cap > PF_NOTICE_MAX_TEXT + 1)
        cap = PF_NOTICE_MAX_TEXT + 1;
    if (cap < 4) {
        out[0] = 0;
        return;
    }
    if (len > cap - 4)
        len = cap - 4;
    for (i = 0; i < len; i++)
        out[i] = text[i];
    out[len] = out[len + 1] = out[len + 2] = '.';
    out[len + 3] = 0;
}

unsigned pf_notice_layout(const char *text, unsigned width, unsigned height, pf_notice_rect *out,
                          unsigned cap)
{
    unsigned n = 0, len = 0, s, pad, box_w, box_h, margin, x0, y0, i, row, col;

    while (text[len] && len < PF_NOTICE_MAX_TEXT)
        len++;
    if (!len || cap < 2)
        return 0;
    /* Two pixels per font pixel at 1080 lines, four at 2160; smaller when
     * the line is wider than the target. */
    s = height / 540 ? height / 540 : 1;
    for (;; s--) {
        pad = 2 * s;
        box_w = len * 6 * s - s + 2 * pad;
        box_h = 7 * s + 2 * pad;
        if ((box_w <= width && box_h <= height) || s == 1)
            break;
    }
    if (box_w > width || box_h > height)
        return 0;
    /* The top right corner, the same margin from the top and the right. */
    margin = height / 30;
    x0 = box_w + margin <= width ? width - box_w - margin : width - box_w;
    y0 = margin + box_h <= height ? margin : height - box_h;
    out[n].x1 = (long)x0;
    out[n].y1 = (long)y0;
    out[n].x2 = (long)(x0 + box_w);
    out[n].y2 = (long)(y0 + box_h);
    n++;
    for (i = 0; i < len; i++) {
        const unsigned char *g = pf_notice_glyph(text[i]);
        unsigned gx = x0 + pad + i * 6 * s;
        for (row = 0; row < 7; row++) {
            for (col = 0; col < 5;) {
                unsigned end = col;
                if (!(g[row] >> (4 - col) & 1)) {
                    col++;
                    continue;
                }
                while (end < 5 && g[row] >> (4 - end) & 1)
                    end++;
                if (n == cap)
                    return 0;
                out[n].x1 = (long)(gx + col * s);
                out[n].y1 = (long)(y0 + pad + row * s);
                out[n].x2 = (long)(gx + end * s);
                out[n].y2 = (long)(y0 + pad + (row + 1) * s);
                n++;
                col = end;
            }
        }
    }
    return n;
}

typedef HRESULT(__stdcall *back_buffer_fn)(void *dev, UINT chain, UINT index, UINT type,
                                           void **surf);
typedef HRESULT(__stdcall *get_rs_fn)(void *dev, UINT state, DWORD *value);
typedef HRESULT(__stdcall *set_rs_fn)(void *dev, UINT state, DWORD value);
typedef HRESULT(__stdcall *get_desc_fn)(void *surf, pf_surface_desc *desc);

static void release(void *obj)
{
    if (obj)
        ((pf_release_fn)PF_VT(obj)[PF_UNK_RELEASE])(obj);
}

void pf_notice_draw(void *dev, const char *text)
{
    static pf_notice_rect rects[PF_NOTICE_MAX_RECTS];
    void **vt = PF_VT(dev), *rt = 0, *bb = 0;
    pf_surface_desc desc;
    pf_viewport vp, full;
    DWORD scissor = 0;
    unsigned n;

    if (FAILED(((pf_get_rt_fn)vt[PF_DEV_GET_RENDER_TARGET])(dev, 0, &rt)) || !rt)
        return;
    if (FAILED(((back_buffer_fn)vt[PF_DEV_GET_BACK_BUFFER])(dev, 0, 0, 0, &bb)) || bb != rt ||
        FAILED(((get_desc_fn)PF_VT(rt)[PF_SURF_GET_DESC])(rt, &desc))) {
        release(bb);
        release(rt);
        return;
    }
    release(bb);
    release(rt);
    n = pf_notice_layout(text, desc.width, desc.height, rects, PF_NOTICE_MAX_RECTS);
    if (!n || FAILED(((pf_ptr_fn)vt[PF_DEV_GET_VIEWPORT])(dev, &vp)))
        return;
    full = vp;
    full.x = full.y = 0;
    full.width = desc.width;
    full.height = desc.height;
    ((get_rs_fn)vt[PF_DEV_GET_RENDER_STATE])(dev, PF_D3DRS_SCISSORTESTENABLE, &scissor);
    if (scissor)
        ((set_rs_fn)vt[PF_DEV_SET_RENDER_STATE])(dev, PF_D3DRS_SCISSORTESTENABLE, 0);
    ((pf_ptr_fn)vt[PF_DEV_SET_VIEWPORT])(dev, &full);
    ((pf_clear_fn)vt[PF_DEV_CLEAR])(dev, 1, rects, PF_D3DCLEAR_TARGET, PF_NOTICE_BG, 0, 0);
    ((pf_clear_fn)vt[PF_DEV_CLEAR])(dev, n - 1, rects + 1, PF_D3DCLEAR_TARGET, PF_NOTICE_FG, 0, 0);
    ((pf_ptr_fn)vt[PF_DEV_SET_VIEWPORT])(dev, &vp);
    if (scissor)
        ((set_rs_fn)vt[PF_DEV_SET_RENDER_STATE])(dev, PF_D3DRS_SCISSORTESTENABLE, scissor);
}
